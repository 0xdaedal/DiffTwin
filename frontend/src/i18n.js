export function detectLocale(preferences = navigator.languages?.length ? navigator.languages : [navigator.language]) {
  return preferences.some((language) => language?.toLowerCase().startsWith("en")) ? "en" : "es";
}

export function translate(locale, source, values = {}) {
  const message = locale === "en" ? english[source] || source : source;
  return message.replace(/\{([a-z]+)\}/gi, (match, name) =>
    Object.hasOwn(values, name) ? values[name] : match
  );
}
